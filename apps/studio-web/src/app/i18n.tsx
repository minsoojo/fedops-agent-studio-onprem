const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ storageKey, children }: { storageKey: string | null; children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => readStoredLocale(storageKey))

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next)
    if (storageKey) window.localStorage.setItem(storageKey, next)
  }, [storageKey])

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const t = useCallback<Translate>((message, values) => {
    const template = locale === 'ko' ? KOREAN[message] ?? message : message
    return interpolate(template, values)
  }, [locale])

  const formatDateTime = useCallback((value: string | number | Date) => (
    new Intl.DateTimeFormat(locale === 'ko' ? 'ko-KR' : 'en-US', {
      dateStyle: 'medium',
      timeStyle: 'medium',
    }).format(new Date(value))
  ), [locale])

  const value = useMemo(
    () => ({ locale, setLocale, t, formatDateTime }),
    [locale, setLocale, t, formatDateTime],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}

function readStoredLocale(storageKey: string | null): Locale {
  if (!storageKey) return 'en'
  return window.localStorage.getItem(storageKey) === 'ko' ? 'ko' : 'en'
}

function interpolate(template: string, values?: Record<string, InterpolationValue>): string {
  if (!values) return template
  return template.replace(/{{(\w+)}}/g, (token, key: string) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : token
  ))
}
